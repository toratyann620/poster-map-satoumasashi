/**
 * 住所文字列の整形。
 *
 * Google の formatted_address は文脈によって形が揺れる:
 *   「日本、〒243-0211 神奈川県厚木市三田１９８１−１」
 *   「〒173-0004 東京都板橋区板橋１丁目９−１０ 保坂ビル 3F」
 *   「しもさとみ」（バス停などのPOIでは施設名だけが返ることがある）
 *
 * 以前は「最後の空白区切りだけを取る」方法で郵便番号を外していたが、
 * それだと建物名や階数が付いた住所では**建物名だけ**が残る
 * （「保坂ビル」「シェブー板橋」等が住所として保存された実例がある）。
 * また検索・ピン打ちの経路では郵便番号を外しておらず、「〒243-…」が
 * そのまま保存され、日次レポートに「〒 1箇所」と出る不具合になった。
 *
 * ここでは前置き（「日本、」と郵便番号）だけを外し、残りは全部残す。
 */
export const normalizeAddress = (raw: string | null | undefined): string => {
    let s = String(raw ?? '').trim();
    s = s.replace(/^日本[、,]?\s*/, '');
    s = s.replace(/^〒?\s*\d{3}[-ー−‐]?\d{4}\s*/, '');
    return s.trim();
};

/**
 * 住所として成立していそうか（都道府県・市区郡のいずれかを含むか）。
 *
 * POIを検索して選ぶと、住所ではなく施設名（「しもさとみ」等）が
 * formatted_address に入っていることがある。その場合は住所欄に入れず、
 * 逆ジオコーディングで正しい住所を引き直す判断に使う。
 */
export const looksLikeAddress = (s: string | null | undefined): boolean => {
    const a = String(s ?? '');
    return /[都道府県]|市|区|郡|町|村/.test(a);
};
